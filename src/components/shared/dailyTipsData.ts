export function tipsForAge(months: number | null): DailyTip[] {
  if (months === null) return dailyTips.filter((t) => t.minMonths === undefined);
  return dailyTips.filter(
    (t) =>
      (t.minMonths === undefined || months >= t.minMonths) &&
      (t.maxMonths === undefined || months < t.maxMonths)
  );
}
